// Helper function to create rich document content
function createContent(nodes: Array<{ type: string; attrs?: Record<string, unknown>; content?: unknown[] }>): Record<string, unknown> {
	return {
		type: "doc",
		content: nodes,
	};
}

// Helper for heading
function h(level: number, text: string): { type: string; attrs: { level: number }; content: Array<{ type: string; text: string }> } {
	return {
		type: "heading",
		attrs: { level },
		content: [{ type: "text", text }],
	};
}

// Helper for paragraph
function p(text: string): { type: string; content: Array<{ type: string; text: string }> } {
	return {
		type: "paragraph",
		content: [{ type: "text", text }],
	};
}

// Helper for placeholder paragraph
function placeholder(description: string): { type: string; content: Array<{ type: string; marks: Array<{ type: string; attrs?: { color: string } }>; text: string }> } {
	return {
		type: "paragraph",
		content: [{
			type: "text",
			marks: [{ type: "italic" }, { type: "textColor", attrs: { color: "#9CA3AF" } }],
			text: `[${description}]`,
		}],
	};
}

